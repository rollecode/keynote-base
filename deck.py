def detect(code):
    if code.lstrip().startswith("{") or re.search(r'^\s*"\w+":', code, re.M):
        return "json"
    if "<!--" in code or re.search(r"<[a-z]+[ >]", code):
        return "markup"
    if "$" in code or "=>" in code or "<?php" in code or "_(" in code:
        return "php"
    return "js"


def highlight(code, lang=None):
    """Tokenise into spans. Small on purpose: four languages, short snippets."""
    lang = lang or detect(code)
    pattern = "|".join([
        r"(?P<comment>//[^\n]*|#[^\n]*|<!--|-->)",
        r"(?P<key>\"[^\"\n]*\"(?=\s*:))",
        r"(?P<string>'[^'\n]*'|\"[^\"\n]*\")",
        r"(?P<keyword>\b(?:" + KEYWORDS[lang] + r")\b|=>)",
        r"(?P<number>\b\d+(?:\.\d+)?\b)",
        r"(?P<func>\b[a-zA-Z_][\w]*(?=\s*\())",
        r"(?P<punct>[{}\[\]();:,<>=|&.-])",
    ])
    out, pos = [], 0
    for m in re.finditer(pattern, code):
        if m.start() > pos:
            out.append(esc(code[pos:m.start()]))
        kind = m.lastgroup
        out.append(f'<span class="t-{kind}">{esc(m.group())}</span>')
        pos = m.end()
    out.append(esc(code[pos:]))
    return "".join(out)


def emit_code_css():
    t = CODE_THEME
    spans = "\n".join(f'.t-{k} {{ color: {v}; }}'
                      for k, v in t.items() if k not in ("bg", "text"))
    return f'''/* Generated by deck.py. Geometry here is what the Keynote bitmaps are
   rendered at, so do not change it by hand. */

pre {{
  box-sizing: border-box;
  margin: 0;
  padding: {CODE_PAD}px {CODE_PAD + 8}px;
  background: {t["bg"]};
  font-family: var(--mono);
  font-size: {CODE_FONT}px;
  line-height: {CODE_LH}px;
  color: {t["text"]};
  white-space: pre;
  overflow: hidden;
}}

.t-comment {{ font-style: italic; }}
{spans}
'''

