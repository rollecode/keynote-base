CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"


def shoot(page, w, h, out_png):
    """One Chrome launch. Launching it per image costs ~40s each, so don't."""
    subprocess.run(
        [CHROME, "--headless", "--disable-gpu", "--hide-scrollbars",
         f"--screenshot={out_png}", f"--window-size={w},{h}", str(page)],
        check=True, capture_output=True)


def crop(sheet, x, y, w, h, out_png):
    subprocess.run(
        ["ffmpeg", "-y", "-loglevel", "error", "-i", str(sheet),
         "-vf", f"crop={w}:{h}:{x}:{y}", "-frames:v", "1", str(out_png)],
        check=True)


def render_code_panels():
    """Every code block on one sheet, then cropped out. Same CSS as the web slide."""
    out = GEN
    tmp = out / "_sheets"
    tmp.mkdir(parents=True, exist_ok=True)

    blocks, y = [], 0
    for n, slide in enumerate(DECK, 1):
        if slide["layout"] != "code":
            continue
        for side in ("left", "right"):
            code = slide[f"{side}_code"]
            h = panel_height(code)
            blocks.append((f"code-{n}-{side}", code, y, h))
            y += h

    body = "".join(
        f'<pre style="height:{h}px">{highlight(c)}</pre>' for _, c, _, h in blocks)
    page = tmp / "code.html"
    page.write_text(f"""<!doctype html><meta charset="utf-8">
<link rel="stylesheet" href="{(ROOT / 'code.css').as_uri()}">
<style>
  html, body {{ margin: 0; padding: 0; background: {CODE_THEME['bg']}; }}
  :root {{ --mono: "Geist Mono", ui-monospace, monospace; }}
  body {{ zoom: {SCALE}; }}
  pre {{ width: {PANEL_W}px; }}
</style>
{body}""")
    sheet = tmp / "code-sheet.png"
    shoot(page, PANEL_W * SCALE, y * SCALE, sheet)
    for name, _, top, h in blocks:
        crop(sheet, 0, top * SCALE, PANEL_W * SCALE, h * SCALE, out / f"{name}.png")
    return len(blocks)


def render_bars():
    """Every footer progress element on one sheet, then cropped out."""
    out = GEN
    tmp = out / "_sheets"
    tmp.mkdir(parents=True, exist_ok=True)

    rows = "".join(
        f'<div class="wrap">{progress_html(n)}</div>'
        for n in range(1, len(DECK) + 1))
    page = tmp / "prog.html"
    page.write_text(f"""<!doctype html><meta charset="utf-8">
<link rel="stylesheet" href="{(ROOT / 'base.css').as_uri()}">
<style>
  html, body {{ margin: 0; padding: 0; background: {GROUND}; }}
  body {{ zoom: {SCALE}; font-family: "Geist", sans-serif; }}
  .wrap {{ display: flex; justify-content: flex-end; align-items: center;
           width: {PROG_W}px; height: {PROG_H}px; }}
</style>
{rows}""")
    sheet = tmp / "prog-sheet.png"
    shoot(page, PROG_W * SCALE, PROG_H * SCALE * len(DECK), sheet)
    for n in range(1, len(DECK) + 1):
        crop(sheet, 0, (n - 1) * PROG_H * SCALE,
             PROG_W * SCALE, PROG_H * SCALE, out / f"prog-{n}.png")


def emit_outline():
    rows = []
    for i, (s, m) in enumerate(zip(DECK, TIMING), 1):
        rows.append(f"| {i} | {s['head']} {s['em']} | {s['layout']} | {m:.1f} |")
    body = "\n".join(rows)
    return f"""# {DECK[0]['head']} {DECK[0]['em']}

Generated by deck.py. Do not edit the running order here; edit DECK in talk.py.

{EVENT}. {VENUE}.
{SLOT_MIN} min slot, {QA_MIN} min Q&A, so {TALK_MIN} min of talking.
{len(DECK)} slides.

## Running order

| # | Slide | Layout | Minute |
| -- | -- | -- | -- |
{body}
{NOTES}"""


